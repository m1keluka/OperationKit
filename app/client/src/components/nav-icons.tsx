interface NavIconProps extends Omit<SVGProps<SVGSVGElement>, 'name'> {
  name: NavIconName
  /** 'solid' is used for the active item (outline→solid, per the showcase). */
  variant?: 'outline' | 'solid'
  /** Outline stroke weight — defaults to 1.75 to match the prior Lucide nav metrics. */
  strokeWidth?: number
}

export function NavIcon({
  name,
  variant = 'outline',
  strokeWidth = 1.75,
  className,
  ...rest
}: NavIconProps) {
  const glyph = GLYPHS[name]
  const useSolid = variant === 'solid' && !!glyph.solid
  return (
    <svg
      viewBox="0 0 24 24"
      aria-hidden="true"
      className={className}
      fill={useSolid ? 'currentColor' : 'none'}
      stroke={useSolid ? 'none' : 'currentColor'}
      strokeWidth={useSolid ? undefined : strokeWidth}
      dangerouslySetInnerHTML={{ __html: useSolid ? glyph.solid! : glyph.outline }}
      {...rest}
    />
  )
}
