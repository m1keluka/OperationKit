/**
 * Transcript redaction at write time (obj 715532).
 *
 * The session wrapper pipes the CLI's stream-json through a tiny standalone
 * Node filter before it is appended to `/home/operator/transcripts/<id>.jsonl`:
 *
 *     claude … < prompt | node cc-redact-stream.mjs >> <id>.jsonl
 *
 * The filter knows the session's secret VALUES only because it inherits the
 * same env the worker already has; the server passes it the NAMES to redact via
 * CC_REDACT_ENV_KEYS. Each known value becomes `[REDACTED:<NAME>]` — the name of
 * the env var the worker can use instead — and high-confidence credential
 * shapes (JWT, PEM, ghp_, sk-…) are replaced too.
 *
 * Partial-message streaming splits text into token deltas, so a value echoed by
 * the model can arrive as `"sb_sec"` + `"ret_abc…"` on two lines that never
 * match on their own. The filter HOLDS BACK consecutive deltas of one content
 * block while their tail could still be the start of a known value, and emits
 * the safe prefix as one merged delta. stream-parser.ts concatenates delta text,
 * so merging is invisible to the UI.
 *
 * The script is generated from this module (patterns come from
 * secret-redaction.ts) and written next to the wrapper at spawn; it has no
 * imports beyond Node built-ins so it runs anywhere the wrapper does.
 */
import fs from 'fs'
import path from 'path'
import { PATTERN_RULES, isSecretEnvEntry, knownSecretNames, MIN_SECRET_LEN } from './secret-redaction.js'

export const FILTER_FILENAME = 'cc-redact-stream.mjs'

/** Generated filter source. Pure function of the shared pattern table. */
export function buildFilterSource(): string {
  const rules = PATTERN_RULES
    .filter(r => r.high && !r.replace)
    .map(r => ({ family: r.family, source: r.re.source, flags: r.re.flags }))
  return `#!/usr/bin/env node
// GENERATED by services/transcript-redact-filter.ts (obj 715532). Do not edit.
const MIN = ${MIN_SECRET_LEN}
const RULES = ${JSON.stringify(rules)}.map(r => ({ family: r.family, re: new RegExp(r.source, r.flags) }))
const CONN = /\\b([a-z][a-z0-9+.-]*:\\/\\/)([^\\s:/@'"]+):([^\\s@/'"]+)@/gi
const esc = s => s.replace(/[.*+?^\${}()|[\\]\\\\]/g, '\\\\$&')

const byValue = new Map()
for (const name of (process.env.CC_REDACT_ENV_KEYS || '').split(',').map(s => s.trim()).filter(Boolean)) {
  const v = process.env[name]
  if (!v || v.length < MIN) continue
  if (!byValue.has(v)) byValue.set(v, name)
  const j = JSON.stringify(v).slice(1, -1)
  if (j !== v && !byValue.has(j)) byValue.set(j, name)
}
const values = [...byValue.keys()].sort((a, b) => b.length - a.length)
const KNOWN = values.length ? new RegExp(values.map(esc).join('|'), 'g') : null

function redact(s) {
  try {
    let out = s
    if (KNOWN) { KNOWN.lastIndex = 0; out = out.replace(KNOWN, v => '[REDACTED:' + byValue.get(v) + ']') }
    for (const r of RULES) { r.re.lastIndex = 0; out = out.replace(r.re, m => m.startsWith('[REDACTED') ? m : '[REDACTED:' + r.family + ']') }
    CONN.lastIndex = 0
    out = out.replace(CONN, (m, a, u, p) => (/^(\\[REDACTED|\\$|\\{)/.test(p) ? m : a + u + ':[REDACTED:CONN_PASSWORD]@'))
    return out
  } catch { return s }
}

/** Length of the longest suffix of s that is a proper prefix of some known value. */
function heldTail(s) {
  let best = 0
  for (const v of values) {
    const max = Math.min(v.length - 1, s.length)
    for (let k = max; k > best; k--) {
      if (s.endsWith(v.slice(0, k))) { best = k; break }
    }
  }
  return best
}

// ── delta hold-back ──
const DELTA_FIELD = { text_delta: 'text', input_json_delta: 'partial_json', thinking_delta: 'thinking' }
let pend = null // { proto, field, key, acc }

function deltaOf(obj) {
  if (!obj || obj.type !== 'stream_event' || !obj.event || obj.event.type !== 'content_block_delta') return null
  const d = obj.event.delta
  const field = d && DELTA_FIELD[d.type]
  if (!field || typeof d[field] !== 'string') return null
  return { field, key: String(obj.event.index) + ':' + d.type + ':' + (obj.session_id || '') + ':' + (obj.parent_tool_use_id || ''), text: d[field] }
}

function emitDelta(p, text) {
  if (!text) return
  const o = JSON.parse(JSON.stringify(p.proto))
  o.event.delta[p.field] = text
  out(JSON.stringify(o) + '\\n')
}

function flush() {
  if (!pend) return
  emitDelta(pend, redact(pend.acc))
  pend = null
}

function onLine(line) {
  if (!KNOWN && !line.includes('content_block_delta')) { out(redact(line)); return }
  let obj = null
  const trimmed = line.trim()
  if (trimmed.startsWith('{') && trimmed.includes('content_block_delta')) { try { obj = JSON.parse(trimmed) } catch { obj = null } }
  const d = obj ? deltaOf(obj) : null
  if (!d || !KNOWN) { flush(); out(redact(line)); return }
  if (pend && pend.key !== d.key) flush()
  if (!pend) pend = { proto: obj, field: d.field, key: d.key, acc: '' }
  pend.acc += d.text
  const red = redact(pend.acc)
  const hold = heldTail(pend.acc)
  if (red !== pend.acc) {
    // A full value landed inside the held text: emit everything redacted.
    emitDelta(pend, red)
    pend = null
    return
  }
  if (hold === 0) { emitDelta(pend, pend.acc); pend = null; return }
  if (hold < pend.acc.length) { emitDelta(pend, pend.acc.slice(0, -hold)); pend.acc = pend.acc.slice(-hold) }
}

function out(s) {
  try { process.stdout.write(s) } catch { process.exit(0) }
}
process.stdout.on('error', () => process.exit(0))

let buf = ''
process.stdin.setEncoding('utf8')
process.stdin.on('data', chunk => {
  buf += chunk
  let i
  while ((i = buf.indexOf('\\n')) >= 0) {
    const line = buf.slice(0, i + 1)
    buf = buf.slice(i + 1)
    try { onLine(line) } catch { out(redact(line)) }
  }
})
process.stdin.on('end', () => {
  try { if (buf) onLine(buf); flush() } catch { /* best effort */ }
})
`
}

/** Write (or refresh) the filter next to the wrapper scripts. Returns its path. */
export function installTranscriptFilter(dir: string): string {
  const file = path.join(dir, FILTER_FILENAME)
  const src = buildFilterSource()
  let current = ''
  try { current = fs.readFileSync(file, 'utf-8') } catch { /* first install */ }
  if (current !== src) {
    fs.mkdirSync(dir, { recursive: true })
    const tmp = `${file}.${process.pid}.tmp`
    fs.writeFileSync(tmp, src, { mode: 0o755 })
    fs.renameSync(tmp, file) // atomic: a running wrapper never sees a half-written script
  }
  try { fs.chmodSync(file, 0o755) } catch { /* owned by another uid — content is current */ }
  return file
}

/**
 * Which env NAMES the filter should redact for this session: anything that
 * looks like a credential plus every name the secrets store knows about.
 * Names only — values stay in the env the session already has.
 */
export function redactEnvKeysFor(env: Record<string, string>): string[] {
  let storeNames: Set<string>
  try { storeNames = new Set(knownSecretNames()) } catch { storeNames = new Set() }
  return Object.keys(env)
    .filter(k => k !== 'CC_REDACT_ENV_KEYS' && (storeNames.has(k) || isSecretEnvEntry(k, env[k])))
    .sort()
}

export function transcriptFilterEnabled(): boolean {
  return process.env.CC_TRANSCRIPT_REDACT !== '0'
}
